const slugTitles: Record<string, string> = {
  terms: 'Пользовательское соглашение',
  privacy: 'Политика конфиденциальности',
  cookies: 'Политика куки',
  offer: 'Публичная оферта',
  reprint: 'Перепечатка',
};

export default function LegalPage() {
  const { slug } = useParams<{ slug: string }>();
  const doc = slug ? legalDocs[slug] : undefined;

  useEffect(() => {
    if (doc) {
      document.title = `${doc.title} — РАМКИ`;
    }
  }, [doc]);

  if (!doc) {
    return (
      <div className="min-h-screen flex items-center justify-center pt-32">
        <div className="text-center">
          <p className="font-serif text-3xl text-[#0f0f0f] mb-4">Страница не найдена</p>
          <Link to="/" className="text-[14px] text-[#555555] hover:text-[#0f0f0f] transition-colors">
            ← На главную
          </Link>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-white">

      {/* Breadcrumbs */}
      <nav aria-label="Хлебные крошки" className="pt-20 sm:pt-24 lg:pt-32 pb-6 px-4 sm:px-6 lg:px-12 border-b border-[#f0f0f0]">
        <ol className="flex flex-wrap items-center gap-1.5 max-w-[1400px] mx-auto text-[12px] text-[#888888]">
          <li><Link to="/" className="hover:text-[#0f0f0f] transition-colors">Главная</Link></li>
          <li aria-hidden="true"><ChevronRight className="w-3 h-3" /></li>
          <li className="text-[#555555]" aria-current="page">{doc.title}</li>
        </ol>
      </nav>

      {/* Navigation tabs between legal docs */}
      <div className="px-0 sm:px-6 lg:px-12 border-b border-[#e5e5e5] overflow-x-auto">
        <div className="max-w-[1400px] mx-auto">
          <div className="flex gap-0 min-w-max">
            {Object.entries(slugTitles).map(([s, label]) => (
              <Link
                key={s}
                to={`/legal/${s}`}
                className={`px-4 py-4 text-[13px] border-b-2 transition-colors whitespace-nowrap ${
                  s === slug
                    ? 'border-[#0f0f0f] text-[#0f0f0f] font-medium'
                    : 'border-transparent text-[#777777] hover:text-[#0f0f0f]'
                }`}
              >
                {label}
              </Link>
            ))}
          </div>
        </div>
      </div>

      {/* Content */}
      <div className="px-4 sm:px-6 lg:px-12 py-10 sm:py-14 lg:py-20">
        <div className="max-w-[720px] mx-auto">
          <header className="mb-12">
            <h1 className="font-serif text-3xl lg:text-4xl font-normal text-[#0f0f0f] mb-3">
              {doc.title}
            </h1>
            <p className="text-[13px] text-[#888888]">Последнее обновление: {doc.updated}</p>
          </header>

          <div>
            {doc.sections.map((section, i) => {
              if (section.h2) return (
                <h2 key={i} className="font-serif text-xl lg:text-2xl font-normal text-[#0f0f0f] mt-12 mb-4 pb-3 border-b border-[#e5e5e5]">
                  {section.h2}
                </h2>
              );
              if (section.h3) return (
                <h3 key={i} className="font-medium text-[16px] text-[#0f0f0f] mt-7 mb-2">
                  {section.h3}
                </h3>
              );
              if (section.p) return (
                <p key={i} className="text-[16px] text-[#333333] leading-[1.8] mb-5">
                  {section.p}
                </p>
              );
              if (section.ul) return (
                <ul key={i} className="mb-5 space-y-2 pl-5">
                  {section.ul.map((item, j) => (
                    <li key={j} className="text-[16px] text-[#333333] leading-[1.7] list-disc list-outside">
                      {item}
                    </li>
                  ))}
                </ul>
              );
              return null;
            })}
          </div>

          <div className="mt-16 pt-8 border-t border-[#e5e5e5]">
            <p className="text-[13px] text-[#888888]">
              Вопросы? Пишите на{' '}
              <a href="mailto:ramki.mag@yandex.ru" className="text-[#0f0f0f] hover:underline">
                ramki.mag@yandex.ru
              </a>
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}
